#!/usr/bin/env python3
"""Generate offline checkout currency tables from the reviewed SIX snapshot.

Run with --check to detect drift. Refresh data/checkout-currencies.json from
the source URL separately, review the change, then regenerate and test.
"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
snapshot = json.loads((ROOT / "data/checkout-currencies.json").read_text())
units = snapshot["minorUnits"]
assert units and all(re.fullmatch(r"[A-Z]{3}", code) and type(digits) is int and 0 <= digits <= 4 for code, digits in units.items())
units = dict(sorted(units.items()))
outputs = {
    ROOT / "apps/control-center/src/lib/checkout-currencies.generated.json": json.dumps(units, indent=2) + "\n",
    ROOT / "apps/vinted-service/internal/vinted/checkout_currencies_generated.go": (
        "// Code generated by scripts/generate-checkout-currencies.py; DO NOT EDIT.\n"
        f"// SIX ISO 4217 list published {snapshot['published']}.\n"
        "package vinted\n\nvar checkoutCurrencyMinorUnits = map[string]int{\n"
        + "".join(f'\t"{code}": {digits},\n' for code, digits in units.items()) + "}\n"
    ),
}
for name, indent in [("background.js", ""), ("page-bridge.js", "  ")]:
    file = ROOT / "apps/vintrack-browser-sync-extension" / name
    source = file.read_text()
    block = (
        f"{indent}// BEGIN GENERATED CHECKOUT CURRENCIES\n"
        f"{indent}// SIX ISO 4217 {snapshot['published']}; generated by scripts/generate-checkout-currencies.py.\n"
        f"{indent}const checkoutCurrencyMinorUnits = {json.dumps(units, separators=(',', ':'))};\n"
        f"{indent}// END GENERATED CHECKOUT CURRENCIES\n"
    )
    pattern = r"(?m)^[ \t]*// BEGIN GENERATED CHECKOUT CURRENCIES\n.*?^[ \t]*// END GENERATED CHECKOUT CURRENCIES\n"
    if re.search(pattern, source, re.S | re.M):
        source = re.sub(pattern, lambda _: block, source, flags=re.S | re.M)
    elif name == "page-bridge.js":
        source = source.replace("(function () {\n", "(function () {\n" + block, 1)
    else:
        source = block + source
    outputs[file] = source
stale = []
for file, expected in outputs.items():
    if args.check:
        if not file.exists() or file.read_text() != expected:
            stale.append(str(file.relative_to(ROOT)))
    else:
        file.write_text(expected)
if stale:
    raise SystemExit("Stale checkout currency tables: " + ", ".join(stale))
print(f"{len(units)} ISO checkout currencies {'verified' if args.check else 'generated'}")
