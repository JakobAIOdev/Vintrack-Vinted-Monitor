import test from "node:test";
import assert from "node:assert/strict";
import { checkConfigText, formatConfigResult } from "./config-check.mjs";

test("detects duplicate keys without exposing values", () => {
    const secret = "do-not-print-this";
    const result = checkConfigText(`AUTH_URL=http://localhost:3000\nAUTH_URL=${secret}\n`);
    assert.match(result.errors.join("\n"), /duplicate key AUTH_URL/);
    assert.doesNotMatch(formatConfigResult(result), new RegExp(secret));
});

test("warns for legacy origins and rejects conflicts", () => {
    const result = checkConfigText("AUTH_URL=https://vintrack.example\nAPP_PUBLIC_URL=https://old.example\n");
    assert.ok(result.warnings.some((item) => item.includes("deprecated")));
    assert.ok(result.errors.some((item) => item.includes("conflicts")));
});

test("validates credential groups and numbers", () => {
    const result = checkConfigText("AUTH_GITHUB_ID=id\nPRICE_WATCH_WORKERS=zero\n");
    assert.ok(result.errors.some((item) => item.includes("AUTH_GITHUB_SECRET")));
    assert.ok(result.errors.some((item) => item.includes("positive integer")));
});

test("requires safe production origins and mandatory secrets", () => {
    const result = checkConfigText("NODE_ENV=production\nAUTH_URL=http://localhost:3000\n");
    assert.ok(result.errors.some((item) => item.includes("AUTH_SECRET")));
    assert.ok(result.errors.some((item) => item.includes("stable HTTPS")));
});

const working = [
    "AUTH_URL=https://vintrack.example.com",
    "VINTRACK_SITE_ADDRESS=vintrack.example.com",
    "AUTH_SECRET=generated",
    "VINTED_SESSION_ENCRYPTION_KEY=generated",
    "AUTH_DISCORD_ID=123456789",
    "AUTH_DISCORD_SECRET=synthetic",
].join("\n");

function withLines(...lines) {
    const replaced = new Set(lines.map((line) => line.split("=")[0]));
    return [
        ...working.split("\n").filter((line) => !replaced.has(line.split("=")[0])),
        ...lines,
    ].join("\n");
}

test("accepts a complete public and a complete local configuration", () => {
    assert.deepEqual(checkConfigText(working).errors, []);
    const local = withLines("AUTH_URL=http://localhost:3000", "VINTRACK_SITE_ADDRESS=http://localhost");
    assert.deepEqual(checkConfigText(local).errors, []);
    // A public domain behind another reverse proxy still needs no Caddy match on localhost.
    assert.deepEqual(checkConfigText(withLines("VINTRACK_SITE_ADDRESS=")).errors, []);
});

test("rejects template secrets and a missing login provider", () => {
    const template = checkConfigText(
        withLines(
            "AUTH_SECRET=your_random_secret_here",
            "AUTH_DISCORD_ID=your_discord_client_id",
            "AUTH_DISCORD_SECRET=your_discord_client_secret",
        ),
    );
    assert.ok(template.errors.some((item) => item.includes("AUTH_SECRET still has its template value")));
    assert.ok(template.warnings.some((item) => item.includes("no login provider")));

    const oidc = withLines(
        "AUTH_DISCORD_ID=",
        "AUTH_DISCORD_SECRET=",
        "AUTH_OIDC_ISSUER=https://id.example.com/",
        "AUTH_OIDC_CLIENT_ID=id",
        "AUTH_OIDC_CLIENT_SECRET=synthetic",
    );
    assert.deepEqual(checkConfigText(oidc).errors, []);
});

test("requires the Caddy site address to match the public origin", () => {
    const mismatch = checkConfigText(withLines("VINTRACK_SITE_ADDRESS=http://localhost"));
    assert.ok(mismatch.errors.some((item) => item.includes("does not match the AUTH_URL hostname")));
    const withPath = checkConfigText(withLines("VINTRACK_SITE_ADDRESS=https://vintrack.example.com/app"));
    assert.ok(withPath.errors.some((item) => item.includes("without a path")));
    assert.deepEqual(checkConfigText(withLines("VINTRACK_SITE_ADDRESS=https://vintrack.example.com")).errors, []);
});

test("requires a Telegram webhook secret Telegram can accept", () => {
    const missing = checkConfigText(withLines("TELEGRAM_BOT_TOKEN=synthetic", "TELEGRAM_WEBHOOK_SECRET="));
    assert.ok(missing.errors.some((item) => item.includes("TELEGRAM_WEBHOOK_SECRET is required")));
    const base64 = checkConfigText(withLines("TELEGRAM_BOT_TOKEN=synthetic", "TELEGRAM_WEBHOOK_SECRET=abc+/def=="));
    assert.ok(base64.errors.some((item) => item.includes("may only contain")));
    assert.ok(!formatConfigResult(base64).includes("abc+/def=="));
    const hex = checkConfigText(withLines("TELEGRAM_BOT_TOKEN=synthetic", "TELEGRAM_WEBHOOK_SECRET=0f".padEnd(88, "a")));
    assert.deepEqual(hex.errors, []);
    // An unused secret generated by make init is fine without a bot.
    assert.deepEqual(checkConfigText(withLines("TELEGRAM_WEBHOOK_SECRET=abcdef0123")).errors, []);
});
